"""Tests for `app.settings`."""

from __future__ import annotations

from urllib.parse import unquote, urlsplit

import pytest

from app.settings import DEFAULT_DATABASE_URL, DEFAULT_REDIS_URL, Settings

_ENV_VARS = (
    "DATABASE_URL",
    "REDIS_URL",
    "COOKIE_SECURE",
    "ALLOWED_ORIGINS",
    "CACHE_TTL_SECONDS",
    "SESSION_TTL_SECONDS",
    # The component form the ECS task definition injects (INF-05). Cleared
    # here too, or a machine that happens to export one of them would change
    # what "zero environment variables set" means.
    "DB_HOST",
    "DB_PORT",
    "DB_NAME",
    "DB_USERNAME",
    "DB_PASSWORD",
    "REDIS_HOST",
    "REDIS_PORT",
    "REDIS_DB",
    "REDIS_TLS",
    "REDIS_AUTH_TOKEN",
)


@pytest.fixture
def clean_env(monkeypatch: pytest.MonkeyPatch) -> None:
    """Removes every setting-related env var so defaults are exercised."""
    for var in _ENV_VARS:
        monkeypatch.delenv(var, raising=False)


def test_settings_load_with_zero_env_vars_set(clean_env: None) -> None:
    """The app must boot with no environment configured at all."""
    settings = Settings.from_env()

    assert settings.database_url
    assert settings.redis_url
    assert settings.cache_ttl_seconds > 0
    assert settings.session_ttl_seconds > 0
    assert settings.allowed_origins


