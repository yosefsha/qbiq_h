def test_partially_configured_database_components_raise(
    monkeypatch: pytest.MonkeyPatch, db_components: None
) -> None:
    """Half a configuration must fail loudly, not quietly become localhost.

    Falling back here is the exact defect this composition exists to close:
    the container would boot, answer, and send every query to a database
    that is not there.
    """
    monkeypatch.delenv("DB_PASSWORD")

    with pytest.raises(ValueError, match="DB_PASSWORD"):
        Settings.from_env()


