def test_redis_auth_token_is_carried_in_the_password_position(
    monkeypatch: pytest.MonkeyPatch, redis_components: None
) -> None:
    monkeypatch.setenv("REDIS_TLS", "true")
    monkeypatch.setenv("REDIS_AUTH_TOKEN", "token")

    settings = Settings.from_env()
    parsed = urlsplit(settings.redis_url)

    assert parsed.scheme == "rediss"
    assert parsed.username == ""
    assert parsed.password == "token"  # nothing to escape in this one
    assert parsed.hostname == "cache.abc123.ng.0001.use1.cache.amazonaws.com"


def test_redis_auth_token_with_reserved_characters_round_trips(
    monkeypatch: pytest.MonkeyPatch, redis_components: None
) -> None:
    token = "to/ke@n#wi:th?%"
    monkeypatch.setenv("REDIS_AUTH_TOKEN", token)

    settings = Settings.from_env()
    parsed = urlsplit(settings.redis_url)

    assert unquote(str(parsed.password)) == token
    assert parsed.hostname == "cache.abc123.ng.0001.use1.cache.amazonaws.com"
    assert parsed.port == 6379


